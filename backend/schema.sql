CREATE DATABASE IF NOT EXISTS myshop;
USE myshop;

CREATE TABLE IF NOT EXISTS types (
  typeId INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(120) NOT NULL,
  PRIMARY KEY (typeId),
  UNIQUE KEY uq_types_name (name)
);

CREATE TABLE IF NOT EXISTS menus (
  menuId INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(180) NOT NULL,
  price DECIMAL(10, 2) NOT NULL,
  isBestSeller BOOLEAN NOT NULL DEFAULT FALSE,
  typeId INT UNSIGNED NOT NULL,
  PRIMARY KEY (menuId),
  KEY idx_menus_typeId (typeId),
  CONSTRAINT fk_menus_type FOREIGN KEY (typeId) REFERENCES types(typeId)
    ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS users (
  userId INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL,
  passwordHash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'USER',
  PRIMARY KEY (userId),
  UNIQUE KEY email (email)
);

CREATE TABLE IF NOT EXISTS ratings (
  ratingId INT UNSIGNED NOT NULL AUTO_INCREMENT,
  userId INT UNSIGNED NOT NULL,
  menuId INT UNSIGNED NOT NULL,
  score TINYINT UNSIGNED NOT NULL,
  PRIMARY KEY (ratingId),
  UNIQUE KEY user_menu_rating (userId, menuId),
  KEY idx_ratings_menuId (menuId),
  CONSTRAINT fk_ratings_user FOREIGN KEY (userId) REFERENCES users(userId) ON DELETE CASCADE,
  CONSTRAINT fk_ratings_menu FOREIGN KEY (menuId) REFERENCES menus(menuId) ON DELETE CASCADE
);
